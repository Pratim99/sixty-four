/* Builds everything needed to hand Sixty-Four to other people:

     dist/site/                    the app as a website, ready to upload to any static host
                                   (GitHub Pages, Netlify, Cloudflare Pages, your own server).
                                   Works on Windows, Mac, iPhone, iPad and Android; can be added to
                                   the home screen as an app; works offline after the first visit.
     dist/Sixty-Four-Windows.zip   the .exe plus a short read-me, for people who prefer a download.

   Run:  node tools/build-site.js */
var fs = require('fs'), path = require('path'), cp = require('child_process'), crypto = require('crypto');

var ROOT = path.resolve(__dirname, '..'), DIST = path.join(ROOT, 'dist'), SITE = path.join(DIST, 'site');

function walk(dir, list) {
  fs.readdirSync(path.join(ROOT, dir)).forEach(function (name) {
    var rel = dir + '/' + name;
    if (fs.statSync(path.join(ROOT, rel)).isDirectory()) walk(rel, list); else list.push(rel);
  });
  return list;
}

/* ---- the website ---- */
var files = ['index.html', 'manifest.webmanifest'].concat(walk('css', []), walk('js', []), walk('vendor', []), walk('icons', []));
fs.rmSync(SITE, { recursive: true, force: true });
var hash = crypto.createHash('sha1');
files.forEach(function (f) {
  var to = path.join(SITE, f), data = fs.readFileSync(path.join(ROOT, f));
  fs.mkdirSync(path.dirname(to), { recursive: true });
  fs.writeFileSync(to, data);
  hash.update(f).update(data);
});
var version = hash.digest('hex').slice(0, 10);

/* The service worker: keeps a copy of every file on the device so the app opens without a connection.
   It always tries the network first, so people get the newest version whenever they are online. */
var sw = [
  "/* Generated by tools/build-site.js. Version " + version + ". */",
  "var CACHE = 'sixtyfour-" + version + "';",
  "var FILES = " + JSON.stringify(['./'].concat(files), null, 1) + ";",
  "self.addEventListener('install', function (e) {",
  "  e.waitUntil(caches.open(CACHE).then(function (c) { return c.addAll(FILES); }).then(function () { return self.skipWaiting(); }));",
  "});",
  "self.addEventListener('activate', function (e) {",
  "  e.waitUntil(caches.keys().then(function (keys) {",
  "    return Promise.all(keys.filter(function (k) { return k !== CACHE; }).map(function (k) { return caches.delete(k); }));",
  "  }).then(function () { return self.clients.claim(); }));",
  "});",
  "self.addEventListener('fetch', function (e) {",
  "  if (e.request.method !== 'GET' || new URL(e.request.url).origin !== location.origin) return;",
  "  e.respondWith(fetch(e.request).then(function (r) {",
  "    if (r && r.ok) { var copy = r.clone(); caches.open(CACHE).then(function (c) { c.put(e.request, copy); }); }",
  "    return r;",
  "  }).catch(function () {",
  "    return caches.match(e.request, { ignoreSearch: true }).then(function (r) { return r || caches.match('./'); });",
  "  }));",
  "});", ""
].join('\n');
fs.writeFileSync(path.join(SITE, 'sw.js'), sw);
fs.writeFileSync(path.join(SITE, '.nojekyll'), '');   // tells GitHub Pages to serve the folder as it is
var bytes = files.reduce(function (n, f) { return n + fs.statSync(path.join(ROOT, f)).size; }, 0);
console.log('Built dist/site: ' + (files.length + 2) + ' files, ' + (bytes / 1048576).toFixed(1) + ' MB, version ' + version + '.');

/* ---- the Windows download ---- */
var exe = path.join(DIST, 'Sixty-Four.exe');
if (!fs.existsSync(exe)) { console.log('No dist/Sixty-Four.exe yet (run node tools/build-exe.js first); skipping the zip.'); process.exit(0); }
var stage = path.join(DIST, 'build', 'Sixty-Four');
fs.rmSync(stage, { recursive: true, force: true });
fs.mkdirSync(stage, { recursive: true });
fs.copyFileSync(exe, path.join(stage, 'Sixty-Four.exe'));
fs.copyFileSync(path.join(ROOT, 'vendor', 'stockfish', 'Copying.txt'), path.join(stage, 'Stockfish licence (GPL-3.0).txt'));
fs.writeFileSync(path.join(stage, 'READ ME FIRST.txt'), [
  'SIXTY-FOUR: learn to see the board',
  '',
  'HOW TO START',
  '  Double-click Sixty-Four.exe. The app opens in its own window.',
  '  Nothing is installed. To remove it, delete this folder.',
  '',
  'IF WINDOWS SHOWS A BLUE "WINDOWS PROTECTED YOUR PC" BOX',
  '  The program is not signed by a big publisher, so Windows is cautious the first time.',
  '  Click "More info", then "Run anyway".',
  '',
  'YOUR PROGRESS',
  '  Lessons done, scores, saved games and puzzles are kept in a file on this computer:',
  '    %APPDATA%\\Sixty-Four\\progress.json',
  '  It is loaded every time you start, whatever happens to your browser.',
  '  To move to another computer, copy that file across, or use "Download a backup" on the home page.',
  '',
  'WHAT IT NEEDS',
  '  Windows 10 or 11 with Microsoft Edge or Google Chrome (Edge comes with Windows).',
  '  No internet connection is needed. Nothing is sent anywhere.',
  '',
  'CLOSING',
  '  Close the window. The program stops by itself a few minutes later.',
  '',
  'LICENCE',
  '  The chess engine inside is Stockfish (https://stockfishchess.org), free software under the',
  '  GNU General Public License version 3; its licence text is in this folder.',
  ''
].join('\r\n'));
var zip = path.join(DIST, 'Sixty-Four-Windows.zip');
fs.rmSync(zip, { force: true });
var r = cp.spawnSync('powershell', ['-NoProfile', '-Command',
  "Compress-Archive -Path '" + stage + "' -DestinationPath '" + zip + "' -Force"], { encoding: 'utf8' });
if (r.status !== 0) { console.error('Could not make the zip: ' + (r.stderr || r.stdout)); process.exit(1); }
console.log('Built dist/Sixty-Four-Windows.zip: ' + (fs.statSync(zip).size / 1048576).toFixed(1) + ' MB.');
